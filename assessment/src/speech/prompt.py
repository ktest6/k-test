"""받아쓰기에 쓰는 지시문.

이 파일이 지키려는 것은 하나다. **들린 대로 적게 하고, 고치지 못하게 한다.**

왜 이것이 그렇게 중요한가:
우리는 응시자의 한국어 실력을 채점한다. 그런데 받아쓰는 기계가 친절하게
문법을 고쳐 주면, 조사를 틀린 응시자와 안 틀린 응시자가 같은 글이 되어 버린다.
그러면 언어 사용 점수는 응시자의 실력이 아니라 기계의 교정 실력을 잰 값이 된다.
받아쓰기에서 한 번 지워진 오류는 뒤 단계에서 되살릴 방법이 없다.

**여기서 인용 검증을 하지 않는 이유**(채점 쪽과 다른 점):
채점의 LLM 판정은 답안 원문과 대조해서 지어낸 인용을 버릴 수 있다.
받아쓰기는 그 '원문'을 만드는 일이라 대조할 글이 없다. 소리와 글자를 코드로
맞대 볼 수는 없기 때문이다. 그래서 검증 대신 **지시로 최대한 막고**,
그래도 남는 한계는 gemini_stt.py 의 설명에 실측 사실로 적어 둔다.
"""

from __future__ import annotations

SYSTEM_INSTRUCTION = """\
당신은 한국어 음성을 들리는 그대로 받아쓰는 기계다.
당신은 교정기가 아니고 번역기도 아니며 채점자도 아니다.

이 음성은 한국어를 배우는 외국인 노동자의 시험 답안이다.
말한 사람이 틀리게 말한 것을 당신이 고치면 그 사람의 시험 점수가 잘못 매겨진다.
틀린 채로 적는 것이 당신의 일이다.

반드시 지킬 규칙:
1. 들린 소리를 그대로 적는다. 문법이 틀려도 고치지 않는다.
2. 조사(은/는/이/가/을/를)와 어미가 틀리게 들리면 틀린 그대로 적는다.
3. 숫자와 낱말을 다른 표기로 바꾸지 않는다. 들린 소리의 글자를 그대로 쓴다.
4. 망설임과 군말(어, 음, 그, 저기)과 같은 말의 반복을 지우지 않는다.
5. 문장을 다듬거나 요약하거나 순서를 바꾸지 않는다.
6. 안 들리는 구간은 [불명] 이라고 적는다. 그럴듯한 말을 지어내지 않는다.
7. 말소리가 하나도 없으면 빈 문자열을 돌려준다. 문장을 만들어 내지 않는다.
8. 받아쓴 글 말고 다른 말(설명, 감상, 요약)을 덧붙이지 않는다.

당신이 고쳐도 되는 것은 없다. 하나도 없다.
"""

#: 지시만으로는 부족한 것이 실측으로 확인돼서 보기(few-shot)를 함께 준다.
#:
#: ※ 다만 **이 보기를 넣어도 아래 두 줄은 그대로 고쳐졌다**(2026-08-02 실측).
#:   소리로는 구별되지 않는 자리라서 지시로 막을 수 있는 문제가 아니다.
#:   그래도 보기를 두는 이유는, 소리로 구별되는 오류(낱말 선택·어순 등)까지
#:   덩달아 다듬는 것은 이것으로 줄어들기 때문이다.
#:   못 막는 것이 무엇인지는 gemini_stt.py 의 설명에 적어 두었다.
USER_PROMPT = """\
이 한국어 음성을 들리는 그대로 받아써라.

이렇게 적어야 한다:
  들린 소리 "안 돼습니다"      -> 적을 글: 안 돼습니다      (X: 안 됐습니다)
  들린 소리 "삼번 라인"        -> 적을 글: 삼번 라인        (X: 3번 라인)
  들린 소리 "기계가 멈추었어요" -> 적을 글: 기계가 멈추었어요 (X: 기계가 멈췄어요)
  들린 소리 "어... 그 저기"     -> 적을 글: 어... 그 저기     (X: 지운다)

오른쪽 괄호 안의 (X) 는 절대 하면 안 되는 일이다.
말한 사람의 잘못을 당신이 고치면 그 사람이 잘못된 점수를 받는다.

결과는 {"transcript": "받아쓴 글"} 형식의 JSON 으로만 답한다.
"""


def build_transcription_prompt(item_prompt: str = "") -> str:
    """받아쓰기 지시문을 만든다.

    문항 지시문(item_prompt)을 함께 주면 그 상황에서 나올 만한 낱말
    (반장님·지게차·비상정지 같은 현장 용어)을 알아듣는 데 도움이 된다.

    다만 **답이 아니라 상황만 알려 준다.** 기대하는 답안을 알려 주면
    기계가 안 들린 자리를 그 답으로 메워 버리고, 그러면 말하지 않은 말로
    점수를 받게 된다. 그래서 지시문만, 그것도 짧게 자른 것만 넘긴다.
    """
    if not item_prompt.strip():
        return USER_PROMPT

    # 지시문이 길면 앞부분만 쓴다. 상황을 알리는 데는 그것으로 충분하다
    situation = item_prompt.strip()[:200]
    return (
        f"{USER_PROMPT}\n"
        f"참고 (말하는 상황이다. 이 글을 받아쓰라는 것이 아니고, "
        f"안 들리는 자리를 이 내용으로 메우라는 것도 아니다):\n{situation}\n"
    )
