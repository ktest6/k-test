-- =========================================================
-- 시험 회차명(round_name) 시스템 자동 생성으로 전환 + 유니크 제약
-- =========================================================
-- 관리자가 직접 입력하던 round_name을 서버가 "{연도}{연도별 순차번호}"
-- 형식(예: 202601, 202602)으로 자동 생성하도록 바꾼다 — 오타로 인한 표기
-- 불일치를 막기 위함 (ExamService.generateRoundName() 참고). 순차번호는
-- soft-delete된 회차도 포함해 절대 재사용하지 않으므로, UNIQUE 제약이
-- 동시 생성 시의 마지막 안전장치 역할을 한다.

alter table tb_exam
  add constraint uq_exam_round_name unique (round_name);

comment on column tb_exam.round_name is
  '회차 식별 코드 — 서버가 자동 생성 (형식: {연도}{연도별 순차번호}, 예: 202601). 관리자가 직접 입력하지 않음.';
