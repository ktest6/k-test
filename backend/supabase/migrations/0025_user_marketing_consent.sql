-- =========================================================
-- 마케팅 정보 수신 동의(선택) 컬럼 추가
-- =========================================================
-- 회원가입 필수 동의 2개(이용약관/개인정보처리방침)에 이어, 선택 동의 1개를
-- 추가한다. 실제 약관 내용/명칭은 아직 확정 전이라 우선 "마케팅 정보 수신
-- 동의"로 가정해서 만든다 — 나중에 다른 항목으로 확정되면 컬럼/필드명만
-- 바꾸면 된다(아직 실 데이터가 없어 비용이 크지 않음).

alter table tb_user
  add column marketing_agreed_at timestamptz;

comment on column tb_user.marketing_agreed_at is '마케팅 정보 수신 동의 시각(선택). 동의 안 했으면 NULL.';
